"""Net field descriptor rows of 6..8 bits that the character count can outgrow (a57, 16 Nov 2026).

The delta coder of the entity and agent states reads a table of field lists (0x141BB3B20, 16 bytes a list: pointer, row count);
a row is 12 bytes {offset, bits, flag}. A row of an integer field with 6, 7 or 8 bits holds numbers below 64, 128, 256 on the wire. The
clientNum fields (offset 0x9C, 6 bits in 24 lists, 8 bits in list 32) are character numbers and have their own sites in agent_capacity.cpp.
With more than 256 characters a character number needs 9 bits, so every other row of 6..8 bits in a list that an agent or its entity can
be written with is widened as well: none of them was proven free of character numbers, a wider field costs only bits on the wire and never
changes a value (the generic delta copies a dword for every field of up to 32 bits).

Lists left alone: 34 (the player state: players only, clients 0..17), 35 (6 rows) and 36 (the player state's second list, FUN_140bb9e10 called
from the player state reader FUN_140bba5a0). Lists that share one table (the generic list serves 11 entity types) are counted once.

    python -B ops/engine/net_rows.py find                     # list the rows (analysed image of the RE lab)
    python -B ops/engine/net_rows.py check                    # the generated table equals the image
    python -B ops/engine/net_rows.py emit -o src/native/agent_capacity_net_rows.inc
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import state_sites as ss  # noqa: E402

LIST_TABLE = 0x141BB3B20
LISTS = 39
SKIPPED_LISTS = (34, 35, 36)
CLIENT_NUM = 0x9C
MIN_BITS, MAX_BITS = 6, 8


def read_lists(img):
    lists = []
    for i in range(LISTS):
        ptr, count = struct.unpack('<QI', img.read(LIST_TABLE + 16 * i, 12))
        lists.append((ptr, count))
    return lists


def rows(img):
    """-> list of dicts {address (of the bits field), offset, bits, lists (the table indexes sharing the list)}, sorted by address."""
    seen, out = {}, []
    for i, (ptr, count) in enumerate(read_lists(img)):
        if i in SKIPPED_LISTS:
            continue
        if ptr in seen:
            seen[ptr]['lists'].append(i)
            continue
        entry = {'ptr': ptr, 'count': count, 'lists': [i]}
        seen[ptr] = entry
        for k in range(count):
            offset, bits, flag = struct.unpack('<III', img.read(ptr + 12 * k, 12))
            if not (MIN_BITS <= bits <= MAX_BITS):
                continue
            if offset == CLIENT_NUM and bits == 6:
                continue                     # patched by the clientNum loops of agent_capacity.cpp
            out.append({'address': ptr + 12 * k + 4, 'offset': offset, 'bits': bits, 'lists': entry['lists']})
    out.sort(key=lambda r: r['address'])
    return out


def client_num_rows(img):
    """The clientNum rows the component patches itself (offset 0x9C, 6 bits): addresses of the bits fields."""
    seen, out = set(), []
    for i, (ptr, count) in enumerate(read_lists(img)):
        if i in SKIPPED_LISTS or ptr in seen:
            continue
        seen.add(ptr)
        for k in range(count):
            offset, bits, _ = struct.unpack('<III', img.read(ptr + 12 * k, 12))
            if offset == CLIENT_NUM and bits == 6:
                out.append(ptr + 12 * k + 4)
    return sorted(out)


def emit_text(rs):
    lines = ['// Generated by ops/engine/net_rows.py emit; do not edit.',
             '// Net field rows of 6..8 bits widened above 256 characters: address of the bits field, field offset, stock bits.']
    for r in rs:
        lines.append('{0x%Xull, 0x%Xu, %du},' % (r['address'], r['offset'], r['bits']))
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('command', choices=['find', 'check', 'emit'])
    ap.add_argument('-o', '--output')
    ap.add_argument('--image')
    args = ap.parse_args()
    image_file, _ = ss.image_path()
    img = ss.Image(args.image or image_file)
    rs = rows(img)
    if args.command == 'find':
        for r in rs:
            print('0x%X offset 0x%X bits %d lists %s' % (r['address'], r['offset'], r['bits'], r['lists']))
        print('%d rows, %d clientNum rows patched by the component' % (len(rs), len(client_num_rows(img))))
    elif args.command == 'emit':
        text = emit_text(rs)
        if args.output:
            with open(args.output, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
        else:
            sys.stdout.write(text)
    else:
        if not args.output:
            print('check needs -o <table> to compare', file=sys.stderr)
            return 2
        have = open(args.output, encoding='utf-8').read()
        if have != emit_text(rs):
            print('the table differs from the image', file=sys.stderr)
            return 1
        print('ok: %d rows equal the image' % len(rs))
    return 0


if __name__ == '__main__':
    sys.exit(main())
