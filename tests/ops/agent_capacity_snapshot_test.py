"""Snapshot entity capacity (a49): every table row, for every accepted agent count, against the shipped code.

agent_capacity_snapshot.inc (generated by ops/engine/snapshot_sites.py from snapshot-sites.json) lists the instruction fields that hold the per-snapshot
entity cap (768), the two list caps (1,024), the ring terms and hunk constants of the server's entity-state ring, the client's parsed-entity ring
multiplier and baseline array, and the 21 instructions that address the cgame snapshot's entity array (+0x4AB8). Offline, for n = 24, 28, ..., 320:
  - the .inc and the JSON agree, every row's instruction is the shipped one and its field holds the stock value;
  - the value each row receives is what agent_capacity.hpp gives (the formulas are pinned in the text), and re-encoding the instruction with it keeps
    its length and decodes to the intended displacement / immediate;
  - the new entity array lies behind the state block, inside snap_size(), and nothing else of the object overlaps it;
  - the 11 bit entity number space cannot be exceeded by the cap, the ring and the hunk hold what the lists can write;
  - the index of the whole image holds no 0x4AB8 field that is in neither the user list nor the other-struct list (the table is complete);
  - no row touches a field another patch, cave window or retarget uses.
Skipped when neither the unpacked code files nor the analysed image exist on the machine (same sources as agent_capacity_sites_test.py).
"""
import importlib.util
import json
import os
import re
import struct
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
HPP = os.path.join(ROOT, 'src', 'native', 'agent_capacity.hpp')
CPP = os.path.join(ROOT, 'src', 'native', 'agent_capacity.cpp')
INC_SNAPSHOT = os.path.join(ROOT, 'src', 'native', 'agent_capacity_snapshot.inc')
JSON_ROWS = os.path.join(ROOT, 'ops', 'engine', 'snapshot-sites.json')
TOOL = os.path.join(ROOT, 'ops', 'engine', 'snapshot_sites.py')

spec = importlib.util.spec_from_file_location('sites_test', os.path.join(HERE, 'agent_capacity_sites_test.py'))
st = importlib.util.module_from_spec(spec)
spec.loader.exec_module(st)
cp = st.cp

COUNTS = list(range(24, 321, 4))
N = 2048
REC = 0x110


def layout(n):
    """agent_capacity.hpp layout, the snapshot part (the formulas are pinned by test_the_hpp_formulas)."""
    s = 1016 + 8 * (n - 24)
    state_bytes = 4 * s + 0x808
    state_offset = 0x3DC78 + n * 0xC0
    entity_offset = state_offset + state_bytes
    return {'state': state_offset, 'entity': entity_offset, 'size': entity_offset + N * REC}


def frame_term():
    return 0xA40 + 3 * (N - 0x300)


def parse_rows(text):
    return [{'field': int(m.group(1), 16), 'width': int(m.group(2)), 'stock': int(m.group(3), 16), 'op': m.group(4)}
            for m in re.finditer(r'^\{(0x[0-9A-F]+)ull, (\d), (0x[0-9A-F]+)u, snapshot_op::(\w+)\},$', text, re.M)]


def value_of(op, n):
    """What the planner (plan_snapshot) writes for each op."""
    return {'cap': N, 'client_shift': 11, 'frame_term': frame_term(), 'records_bytes': N * REC, 'frame_bytes': frame_term() * REC,
            'baseline_bytes': N * REC + 0x1000, 'client_ring': N, 'entity_offset': layout(n)['entity']}[op]


class SnapshotRows(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.image, cls.source = st.find_image()
        cls.hpp = open(HPP, encoding='utf-8').read()
        cls.cpp = open(CPP, encoding='utf-8').read()
        cls.inc = parse_rows(open(INC_SNAPSHOT, encoding='utf-8').read())
        cls.table = json.load(open(JSON_ROWS, encoding='utf-8'))['rows']
        cls.cs = cp._cs()

    def test_the_hpp_formulas(self):
        for text in ('constexpr std::uint32_t stock_snapshot_entities = 0x300, stock_snapshot_list = 0x400, entity_record_bytes = 0x110;',
                     'constexpr std::uint32_t snapshot_entities = 2048, snapshot_entities_shift = 11;',
                     'constexpr std::uint32_t stock_ring_frame_term = 0xA40;',
                     'constexpr std::uint32_t ring_frame_term = stock_ring_frame_term + 3 * (snapshot_entities - stock_snapshot_entities);',
                     'constexpr std::uint32_t stock_client_ring_per_frame = 0x258, client_ring_per_frame = snapshot_entities;',
                     'constexpr std::uint32_t snap_state_offset() const { return 0x3DC78 + agents * 0xC0; }',
                     'constexpr std::uint32_t snap_entity_offset() const { return snap_state_offset() + state_bytes(); }',
                     'constexpr std::uint32_t snap_size() const { return snap_entity_offset() + snapshot_entities * entity_record_bytes; }'):
            self.assertIn(text, self.hpp)

    def test_the_cap_is_the_entity_number_space(self):
        # the list ends with 0x7FF in 11 bits: entity numbers 0..0x7FE, so a snapshot holds at most 2,047 records and 2,048 cannot be reached
        self.assertEqual(1 << 11, N)
        self.assertGreater(N, 0x7FF)

    def test_the_ring_holds_what_the_lists_can_write(self):
        # server: records = frames x frame term + clients x N (the hunk term clients x N x 0x110 and frames x term x 0x110 follow the same numbers)
        for frames, clients in ((16, 16), (16, 18), (4, 1)):
            ring = frames * frame_term() + clients * N
            self.assertGreaterEqual(ring, frames * N + clients * N if clients <= 4 else frames * 4 * N, (frames, clients))
            self.assertEqual(ring * REC, frames * (frame_term() * REC) + clients * (N * REC), 'the hunk constants equal the ring bytes')
        # the stock ring is a subset of the grown ring
        self.assertGreater(frame_term(), 0xA40)
        # client: frames x N records: one full snapshot a frame
        self.assertGreaterEqual(16 * N, 16 * 746)

    def test_the_entity_array_lies_behind_the_state_block(self):
        for n in COUNTS:
            lay = layout(n)
            s = 1016 + 8 * (n - 24)
            self.assertEqual(lay['entity'], lay['state'] + 4 * s + 0x808)
            self.assertGreaterEqual(lay['entity'], lay['state'] + 0x17E8, 'behind the block at its stock size')
            self.assertEqual(lay['size'], lay['entity'] + N * REC)
            self.assertEqual(lay['entity'] % 8, 0x4AB8 % 8, 'the shipped alignment of the array is kept')
            self.assertLess(2 * lay['size'], 0x7FFFFFFF)

    def test_the_inc_is_the_json(self):
        self.assertEqual(len(self.inc), len(self.table))
        self.assertEqual(len(self.table), 33)
        for a, b in zip(self.inc, self.table):
            self.assertEqual((a['field'], a['width'], a['stock'], a['op']), (b['field'], b['width'], b['stock'], b['op']))
        self.assertEqual([r['field'] for r in self.inc], sorted(r['field'] for r in self.inc))
        self.assertEqual(len({r['field'] for r in self.inc}), len(self.inc), 'one row a field')
        enum = re.search(r'enum class snapshot_op[^{]*\{([^}]*)\}', self.cpp).group(1)
        self.assertEqual(sorted({r['op'] for r in self.inc}), sorted(x for x in re.findall(r'\w+', enum) if x in {r['op'] for r in self.inc}))
        entities = [r for r in self.inc if r['op'] == 'entity_offset']
        self.assertEqual(len(entities), 21)
        self.assertTrue(all(r['stock'] == 0x4AB8 for r in entities))

    def test_every_op_has_a_case_in_the_planner(self):
        body = self.cpp.split('void plan_snapshot()')[1].split('// ---- 3d.')[0]
        for op in {r['op'] for r in self.inc}:
            self.assertIn('snapshot_op::' + op, body, f'plan_snapshot handles {op}')
        self.assertIn('plan_snapshot();', self.cpp.split('void post_unpack() override')[1])
        self.assertIn('#include "agent_capacity_snapshot.inc"', self.cpp)

    def test_every_row_is_the_shipped_instruction_with_the_stock_field(self):
        if self.image is None:
            self.skipTest('no unpacked code files or analysed image on this machine')
        for r in self.table:
            raw = self.image.read(r['at'], len(r['bytes']) // 2)
            self.assertEqual(raw.hex(), r['bytes'], f"{r['at']:#x}: the shipped bytes differ from the table")
            ins = next(self.cs.disasm(raw, r['at']))
            self.assertEqual(ins.size, len(raw), f"{r['at']:#x}: not one whole instruction")
            off = r['field'] - r['at']
            self.assertTrue(0 <= off <= len(raw) - r['width'])
            self.assertEqual(int.from_bytes(raw[off:off + r['width']], 'little'), r['stock'], f"{r['field']:#x}: field")

    def reencode(self, r, value):
        raw = bytearray(self.image.read(r['at'], len(r['bytes']) // 2))
        raw[r['field'] - r['at']:r['field'] - r['at'] + r['width']] = value.to_bytes(r['width'], 'little')
        ins = next(self.cs.disasm(bytes(raw), r['at']))
        self.assertEqual(ins.size, len(raw), f"{r['at']:#x}: the re-encoded instruction changes length")
        return ins

    def decoded(self, ins, r):
        from capstone import x86_const as X
        if ins.encoding.imm_size and r['field'] - r['at'] == ins.encoding.imm_offset:
            return [o.imm for o in ins.operands if o.type == X.X86_OP_IMM][-1]
        return next(o.mem.disp for o in ins.operands if o.type == X.X86_OP_MEM)

    def test_every_value_for_every_count(self):
        if self.image is None:
            self.skipTest('no unpacked code files or analysed image on this machine')
        for n in COUNTS:
            for r in self.table:
                want = value_of(r['op'], n)
                ins = self.reencode(r, want)
                row = f"{n} agents, {r['at']:#x} {r['text']}"
                self.assertEqual(self.decoded(ins, r) & 0xFFFFFFFF, want, row)
                if r['op'] == 'client_shift':
                    self.assertTrue(r['text'].startswith('shl') and 0 < want < 32, row)
                self.assertLess(want, 0x7FFFFFFF if r['width'] == 4 else 0x100, row)

    def test_the_server_hunk_constants_are_the_ring_bytes(self):
        if self.image is None:
            self.skipTest('no unpacked code files or analysed image on this machine')
        by = {r['op']: r for r in self.table if r['op'] in ('frame_bytes', 'baseline_bytes', 'frame_term')}
        self.assertEqual(by['frame_term']['stock'] * REC, by['frame_bytes']['stock'], 'stock: frames x 0xA40 x 0x110')
        self.assertEqual(by['baseline_bytes']['stock'], 0x400 * REC + 0x1000)
        self.assertEqual(value_of('frame_bytes', 24), frame_term() * REC)
        # allocations are rounded to 0x80: the grown constants are multiples of 0x80 so the rounding stays exact
        for op in ('records_bytes', 'frame_bytes', 'baseline_bytes'):
            self.assertEqual(value_of(op, 24) % 0x80, 0, op)

    def test_the_index_holds_no_unclassified_0x4ab8(self):
        if self.image is None:
            self.skipTest('no unpacked code files or analysed image on this machine')
        spec2 = importlib.util.spec_from_file_location('snapshot_sites', TOOL)
        tool = importlib.util.module_from_spec(spec2)
        spec2.loader.exec_module(tool)
        try:
            hits = tool.index_hits()
        except Exception as e:  # no instruction index on this machine
            self.skipTest(f'no instruction index: {e}')
        named = set(tool.SNAPSHOT_USERS) | set(tool.OTHER_0X4AB8)
        self.assertEqual([hex(at) for at, _, _ in hits if at not in named], [])
        self.assertEqual(sorted(hex(a) for a in tool.SNAPSHOT_USERS), sorted(hex(r['at']) for r in self.table if r['op'] == 'entity_offset'))

    def test_no_overlap_with_any_other_patch(self):
        sites, _ = st.extract_sites(self.cpp)
        spans = []
        for x in sites:
            width = 4 if x['kind'] == 'rip' else (len(x['before']) if x['kind'] == 'block' else x['width'])
            spans.append((x['address'], x['address'] + width, 'site'))
        for name in ('agent_capacity_caves.inc', 'agent_capacity_caves_rewind.inc', 'agent_capacity_caves_wide.inc',
                     'agent_capacity_caves_mask.inc', 'agent_capacity_caves_guard.inc', 'agent_capacity_caves_interp.inc'):
            for c in st.parse_inc(open(os.path.join(ROOT, 'src', 'native', name), encoding='utf-8').read()):
                spans.append((c['start'], c['start'] + len(c['old']), 'cave ' + name))
                spans.extend((t['field'], t['field'] + 4, 'retarget') for t in c['retargets'])
        for t in st.FRAME_TABLES:
            for x in st.FrameGrow.parse_fields(t['fields']):
                spans.append((x['address'], x['address'] + x['width'], 'frame field'))
        for name, kind in (('agent_capacity_state.inc', 'state row'), ('agent_capacity_pools.inc', 'pool row'), ('agent_capacity_sound.inc', 'sound row')):
            for m in re.finditer(r'^\{(0x[0-9A-F]+)ull', open(os.path.join(ROOT, 'src', 'native', name), encoding='utf-8').read(), re.M):
                spans.append((int(m.group(1), 16), int(m.group(1), 16) + 4, kind))
        for r in self.inc:
            spans.append((r['field'], r['field'] + r['width'], 'snapshot row'))
        spans.sort()
        clash = [(hex(a[0]), a[2], hex(b[0]), b[2]) for a, b in zip(spans, spans[1:]) if a[1] > b[0]]
        self.assertEqual(clash, [])


    def test_snapshot_entities_default_on_with_opt_out(self):
        # FE21: a usermap client ended its level at the 769th snapshot record; the cap is raised unless -no-snapshot-entities / IW7_SNAPSHOT_ENTITIES=0
        text = self.cpp if isinstance(self.cpp, str) else open(os.path.join(ROOT, 'src', 'native', 'agent_capacity.cpp'), encoding='utf-8').read()
        self.assertIn('has_flag("no-snapshot-entities")', text)
        self.assertIn('env_off(L"IW7_SNAPSHOT_ENTITIES")', text)
        self.assertNotIn('if (env_switch("snapshot-entities", L"IW7_SNAPSHOT_ENTITIES")) snapshot_only();', text)


if __name__ == '__main__':
    unittest.main()
