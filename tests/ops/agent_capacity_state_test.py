"""The replicated scriptable state budget (a39): every table row, for every accepted agent count, against the shipped code.

agent_capacity_state.inc (generated by ops/engine/state_sites.py from state-sites.json) lists 4-byte instruction fields that depend on the budget
of ScriptableSv's replicated state (1,016 dwords; S = 1,016 + 8 x (n - 24) with -agent-capacity n). Offline, for n = 24, 28, ..., 232:
  - the .inc and the JSON agree, every row's instruction is the shipped one (bytes decoded) and its field holds the stock value;
  - the value each row receives is the one the layout of agent_capacity.hpp gives (mirrored here, the text of the formulas is pinned);
  - re-encoding the instruction with the new value decodes to the intended displacement / immediate / target (a rip or rva reference lands on
    the relocated block at the mapped offset);
  - no row touches a field another patch, cave window or retarget uses.
Skipped when neither the unpacked code files nor the analysed image exist on the machine (same sources as agent_capacity_sites_test.py).
"""
