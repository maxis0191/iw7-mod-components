"""Thread ids and thread selves beyond u16 (a79): the rows of script_variables_threads.inc against the shipped code, the widening rule, the table B proof, the component's refusals.

The .inc is generated by `ops/engine/variable_sites.py thread-rows` / `emit-threads` (variable-threads.json). Offline checks:
  - the .inc, the JSON and the widening rule agree; every row widens one byte for one byte;
  - every row is the shipped instruction (needs the analysed image: skipped without);
  - table B: the 20 references of variable-sites.json lie in ten functions, and the component replaces every one of them with the refusal;
  - no row touches a byte another patch of the component uses (the cave windows of script_variables.cpp);
  - the thread allocation sites hand the self over, the class and client arrays stay low.
"""
import json
import os
import re
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'ops', 'engine'))
INC = os.path.join(ROOT, 'src', 'native', 'script_variables_threads.inc')
CPP = os.path.join(ROOT, 'src', 'native', 'script_variables.cpp')
ROWS = os.path.join(ROOT, 'ops', 'engine', 'variable-threads.json')
STAGE1 = os.path.join(ROOT, 'ops', 'engine', 'variable-sites.json')


def parse_inc(text):
    return [tuple(int(x, 16) if x.lower().startswith('0x') else int(x) for x in re.findall(r'0x[0-9A-Fa-f]+|\d+', line)) for line in text.split('\n') if line.startswith('{')]


class ThreadRows(unittest.TestCase):
    def setUp(self):
        self.json = json.load(open(ROWS))
        self.inc = parse_inc(open(INC).read())
        self.cpp = open(CPP, encoding='utf-8').read()

    def test_inc_matches_json(self):
        flat = []
        for r in self.json['rows']:
            stock, new = bytes.fromhex(r['stock']), bytes.fromhex(r['new'])
            self.assertEqual(len(stock), len(new))
            for k in range(0, len(stock), 8):
                flat.append((r['at'] + k, len(stock[k:k + 8]), int.from_bytes(stock[k:k + 8], 'little'), int.from_bytes(new[k:k + 8], 'little')))
        self.assertEqual(flat, self.inc)

    def test_counts(self):
        kinds = {}
        for r in self.json['rows']:
            kinds[r['kind']] = kinds.get(r['kind'], 0) + 1
        self.assertEqual(kinds, {'caller': 42, 'field_1C70': 4, 'name': 2, 'chain': 1, 'return': 2, 'free': 1, 'field_1A24': 9, 'field_test': 1})
        self.assertEqual(self.json['problems'], [])

    def test_widening_rule(self):
        import variable_sites as vs
        for r in [r for r in self.json['rows'] if r['kind'] != 'name']:
            stock = bytes.fromhex(r['stock'])
            self.assertEqual(vs.widen_bytes(stock).hex(), r['new'])
            self.assertEqual(len(stock), len(bytes.fromhex(r['new'])))
            self.assertEqual(bytes.fromhex(r['new'])[0], 0x90)
        self.assertEqual(vs.widen_bytes(bytes.fromhex('0fb7c3')).hex(), '908bc3')                 # movzx eax,bx -> mov eax,ebx
        self.assertEqual(vs.widen_bytes(bytes.fromhex('668983701c0000')).hex(), '908983701c0000')   # mov word [rbx+0x1c70],ax -> dword
        self.assertEqual(vs.widen_bytes(bytes.fromhex('410fb74c2d02')).hex(), '90418b4c2d02')       # REX movzx -> nop ; REX mov

    def test_name_decodes(self):
        # the object key name -> id decode keeps the full name: ebx = name - 0x40000 and edi = name, the registers the next instructions use
        try:
            import capstone
        except ImportError:
            self.skipTest('no capstone')
        md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
        rows = {r['at']: r for r in self.json['rows'] if r['kind'] == 'name'}
        self.assertEqual(sorted(rows), [0x140C0446E, 0x140C09459])
        text = lambda h, at: [(i.mnemonic + ' ' + i.op_str).strip() for i in md.disasm(bytes.fromhex(h), at)]
        self.assertEqual(text(rows[0x140C09459]['new'], 0x140C09459), ['add edx, eax', 'lea ebx, [rdx - 0x40000]', 'mov edi, edx', 'nop', 'nop'])
        self.assertEqual(text(rows[0x140C0446E]['new'], 0x140C0446E), ['add ecx, eax', 'lea ebx, [rcx - 0x40000]', 'mov edx, ecx', 'mov ecx, r15d', 'nop', 'nop'])
        self.assertEqual(text(rows[0x140C09459]['stock'], 0x140C09459), ['add dx, ax', 'movzx ebx, dx', 'lea edi, [rbx + 0x40000]'])

    def test_rows_against_the_image(self):
        try:
            import state_sites as ss
            img = ss.Image(ss.image_path()[0])
        except Exception:
            self.skipTest('no analysed image')
        for r in self.json['rows']:
            self.assertEqual(img.read(r['at'], r['length']).hex(), r['stock'], '%X' % r['at'])
            self.assertEqual(r['length'], len(r['stock']) // 2)

    def test_table_b_is_only_in_the_refused_functions(self):
        stage1 = json.load(open(STAGE1))
        funcs = sorted({r['func'] for r in stage1['refs'] if r['region'] == 'B'})
        listed = sorted(int(x, 16) for x in re.findall(r'\{(0x[0-9A-F]+)ull, \{0x', self.cpp[self.cpp.index('b_functions'):]))
        self.assertEqual(funcs, listed)
        self.assertIn('refuse_save_load', self.cpp)
        self.assertEqual(sum(1 for r in stage1['refs'] if r['region'] == 'B'), 20)

    def test_allocation_classes(self):
        self.assertIn('redirect_thread_alloc(0x140C043C5ull, false, 0)', self.cpp)
        self.assertIn('redirect_thread_alloc(0x140C0458Dull, false, 1)', self.cpp)
        self.assertIn('redirect_thread_alloc(0x140C04523ull, true, 2)', self.cpp)
        self.assertIn('for (const auto site : {0x140C096C6ull, 0x140C096EFull})', self.cpp)             # class arrays stay low
        self.assertIn('alloc_array_low', self.cpp)                                                       # client arrays stay low
        self.assertNotIn('thread_guard_check', self.cpp)

    def test_no_row_in_a_cave_window(self):
        windows = [(0x140C093A4, 6), (0x140C0948D, 9), (0x140C08E1D, 12)]
        for r in self.json['rows']:
            for start, length in windows:
                self.assertFalse(r['at'] < start + length and r['at'] + r['length'] > start, '%X' % r['at'])


if __name__ == '__main__':
    unittest.main()
