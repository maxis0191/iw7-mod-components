        for fragment in ('if (wide)       // the children counters', 'if (wide) {      // more than 4 segments', 'if (wide) entry_hook(0x140C09280ull', 'if (wide) {      // the counters of the children in use'):
            self.assertIn(fragment, self.cpp)
        self.assertRegex(open(HPP, encoding='utf-8').read(), r'default_segments = 8')

