"""More than 4 child segments (a67): the rows of script_variables_segments.inc against the shipped code, the values per segment count, the caves, the plan of 4 segments.

The .inc is generated by `ops/engine/variable_sites.py segment-rows` / `emit-segments` (variable-segments.json). Offline checks:
  - the .inc, the JSON and the census agree (counts: 118 `and r,3`, 4 loop bounds, 10 counter references);
  - every row is the shipped instruction with the stock field (needs the analysed image: skipped without);
  - no row touches a byte another patch of the capacity component, a cave window or an iw7-mod hook window uses;
  - the values every segment count (4, 8, 16) needs: ids, key names and integer keys stay apart, tables fit within 2 GB, the low pool, the shift of the key, the read back cave;
  - the component applies the rows only with more than 4 segments, so that 4 segments is the previous build.
"""
