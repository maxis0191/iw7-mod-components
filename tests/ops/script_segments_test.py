    def test_every_bucket_shift_takes_its_segment_from_a_patched_and(self):
        """The hash shift `shl r,bits` of the segment (15 sites, a62): its operand is `parent & 3`; every one of those `and` is a row of this list."""
        image_file = os.path.join(os.environ.get('IW7_RE_LAB', os.path.join(os.path.expanduser('~'), 'Documents', 'IW7-RE-Lab')), 'engine', 'image', 'iw7_ship_live.exe')
        if not os.path.exists(image_file):
            self.skipTest('no analysed image')
        import variable_sites as vs
        import state_sites as ss
        image_file, db_file = ss.image_path()
        if not os.path.exists(db_file):
            self.skipTest('no engine database')
        img, md = ss.Image(image_file), ss.cs()
        md.detail = True
        bucket = open(os.path.join(ROOT, 'src', 'native', 'script_variables_buckets.inc'), encoding='utf-8').read()
        fields = {int(x, 16) for x in re.findall(r'0x([0-9A-F]+)ull', re.search(r'BUCKET_SHLS\n(.*?)#endif', bucket, re.S).group(1))}
        pieces = vs.complete_ranges(img, md, db_file)
        shl_at = {i.address for _, il in pieces for i in il if i.mnemonic == 'shl' and i.address + i.encoding.imm_offset in fields}
        self.assertEqual(len(shl_at), 15)
        mask_ats = {m['at'] for m in self.data['masks']}
