"""The client's character proxy list (a47): every table row and the grown frame, for every accepted agent count, against the shipped code.

The list (stock 140 entries, FUN_1405527E0 appends with no bound; run a44-m2 crashed at the 141st) lives in eight static tables behind the counts at
0x144B47820. agent_capacity_sound.inc (generated by ops/engine/sound_sites.py from sound-sites.json) lists the 92 four-byte instruction fields of ten functions
that name a table or the entry count 140. Offline, for n = 24..232:
  - the .inc and the JSON agree, every row's instruction is the shipped one and its field holds the stock value;
  - the size follows from the entity space (2,047 numbers less the 16 corpse entities, rounded to the lookup's step of five), holds every character and the
    actor pool at every count, and the tables fit the block;
  - the value each row receives re-encodes to the intended displacement / immediate / rip target;
  - FUN_1405532D0's grown frame: its two arrays (u32 selected[N], N * 16 bytes) fit, the second array's base moves up by the first one's growth, the cookie
    sits behind the second array, the planner's fields and the three `lea` rows do not overlap each other or any other patch.
Skipped when neither the unpacked code files nor the analysed image exist on the machine.
"""
import importlib.util
import json
import os
import re
import struct
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
HPP = os.path.join(ROOT, 'src', 'native', 'agent_capacity.hpp')
CPP = os.path.join(ROOT, 'src', 'native', 'agent_capacity.cpp')
NATIVE = os.path.join(ROOT, 'src', 'native')
INC = os.path.join(NATIVE, 'agent_capacity_sound.inc')
JSON_ROWS = os.path.join(ROOT, 'ops', 'engine', 'sound-sites.json')
FRAME_JSON = os.path.join(ROOT, 'ops', 'engine', 'caves', 'frame-1405532d0.frame.json')

spec = importlib.util.spec_from_file_location('sites_test', os.path.join(HERE, 'agent_capacity_sites_test.py'))
st = importlib.util.module_from_spec(spec)
spec.loader.exec_module(st)
cp = st.cp
spec = importlib.util.spec_from_file_location('sound_sites', os.path.join(ROOT, 'ops', 'engine', 'sound_sites.py'))
ss = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ss)

COUNTS = list(range(24, 233, 4))
STOCK = 140
ENTRIES = (0x7FF - 16 + 4) // 5 * 5          # entity numbers less the corpse entities, rounded up to the lookup's step
SELECTED = (4 * ENTRIES + 15) & ~15          # u32 selected[] in the frame, rounded to 16
SHIFT = SELECTED - 4 * STOCK
EXTRA = SHIFT + 16 * (ENTRIES - STOCK)
SIZES = {'T0': 8, 'T1': 0x30, 'A': 16, 'B': 16, 'T3': 8, 'T4': 8, 'T5': 8, 'T6': 8}


def parse_rows(text):
    rows = []
    for m in re.finditer(r'^\{(0x[0-9A-F]+)ull, (\d), (0x[0-9A-F]+)(?:ull|u), (\d+), sound_op::(\w+), sound_table::(\w+), (-?\d+)\},$', text, re.M):
        rows.append({'field': int(m.group(1), 16), 'form': int(m.group(2)), 'stock': int(m.group(3), 16), 'tail': int(m.group(4)),
                     'op': m.group(5), 'table': m.group(6), 'offset': int(m.group(7))})
    return rows


def parse_frame(text):
    return [(int(m.group(1), 16), int(m.group(2)), int(m.group(3), 16), int(m.group(4)), int(m.group(5)), m.group(6) == 'true')
            for m in re.finditer(r'^\{(0x[0-9a-f]+)ull, (\d), (0x[0-9a-f]+)u, (\d+), (-?\d+), (true|false)\},$', text, re.M | re.I)]


class Rows(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.image, cls.source = st.find_image()
        cls.hpp = open(HPP, encoding='utf-8').read()
        cls.cpp = open(CPP, encoding='utf-8').read()
        cls.inc = parse_rows(open(INC, encoding='utf-8').read())
        data = json.load(open(JSON_ROWS, encoding='utf-8'))
        cls.table, cls.outside = data['rows'], data['outside']
        cls.cs = cp._cs()

    def test_the_hpp_formulas(self):
        for text in ('constexpr std::uint32_t stock_proxy_entries = 140, proxy_entity_numbers = 0x7FF, proxy_corpse_entities = 16, proxy_actor_pool = 38;',
                     'constexpr std::uint32_t proxy_list_most = proxy_entity_numbers - proxy_corpse_entities;',
                     'constexpr std::uint32_t proxy_list_entries = (proxy_list_most + 4) / 5 * 5;',
                     'constexpr std::uint32_t proxy_selected_bytes = (4 * proxy_list_entries + 15) & ~15u;',
                     'constexpr std::uint32_t proxy_frame_shift = proxy_selected_bytes - 4 * stock_proxy_entries;',
                     'constexpr std::uint32_t proxy_frame_extra = proxy_frame_shift + 16 * (proxy_list_entries - stock_proxy_entries);'):
            self.assertIn(text, self.hpp)
        self.assertEqual(ss.STOCK, STOCK)
        self.assertEqual({k: v[1] for k, v in ss.TABLES.items()}, SIZES)

    def test_the_size_holds_every_character_for_every_count(self):
        corpses = 16
        actors = 38
        for n in COUNTS:
            characters = 18 + n
            map_start = characters + corpses
            self.assertLessEqual(characters + actors, ENTRIES - 4, f'{n} agents: characters and the actor pool fit the list')
            self.assertLess(map_start, 0x7FF)
        self.assertEqual(ENTRIES % 5, 0)
        self.assertEqual(ENTRIES, 2035)
        # entries are distinct entities: never more than the entity numbers that are not corpses
        self.assertGreaterEqual(ENTRIES, 0x7FF - 16)
        self.assertEqual(sum(SIZES.values()), 120)
        self.assertLess(ENTRIES * 120, 300 * 1024)

    def test_the_inc_is_the_json(self):
        self.assertEqual(len(self.inc), len(self.table))
        self.assertEqual(len(self.inc), 92)
        for a, b in zip(self.inc, self.table):
            self.assertEqual((a['field'], a['form'], a['stock'], a['tail'], a['op'], a['table'] if a['table'] != 'none' else '', a['offset']),
                             (b['field'], b['form'], b['stock'], b['tail'], b['op'], b['table'], b.get('offset', 0)))
        self.assertEqual([r['field'] for r in self.inc], sorted(r['field'] for r in self.inc))
        self.assertEqual(len({r['field'] for r in self.inc}), len(self.inc), 'one row a field')
        enum = re.search(r'enum class sound_op[^{]*\{([^}]*)\}', self.cpp).group(1)
        for op in {r['op'] for r in self.inc}:
            self.assertIn(op, re.findall(r'\w+', enum))
        tables = re.findall(r'\w+', re.search(r'enum class sound_table[^{]*\{([^}]*)\}', self.cpp).group(1))
        for t in {r['table'] for r in self.inc}:
            self.assertIn(t, tables)

    def test_every_table_and_every_kind_of_value_has_rows(self):
        by = {}
        for r in self.table:
            by.setdefault(r['table'] or r['op'], 0)
            by[r['table'] or r['op']] += 1
        for key in ('T0', 'T1', 'A', 'B', 'T3', 'T4', 'T5', 'T6', 'n', 'n2', 'n8', 'n16'):
            self.assertGreater(by.get(key, 0), 0, key)
        self.assertEqual(sum(by.values()), 92)
        # value rows carry the stock multiple of 140
        for r in self.table:
            if r['op'] != 'ref':
                want = {'n': 140, 'n2': 280, 'n8': 1120, 'n16': 2240}[r['op']]
                self.assertEqual(r['stock'] if r['stock'] < 0x80000000 else 0x100000000 - r['stock'], want)
        # nothing outside the ten functions in live code
        self.assertEqual([o[0] for o in self.outside], ['0x14c16ae5c'])

    def test_the_cpp_applies_the_table(self):
        for text in ('plan_proxy_list();', '#include "agent_capacity_sound.inc"', 'proxy_list = reserve(total);',
                     'rip(s.field, static_cast<std::uintptr_t>(s.stock), target, s.tail)', 'rva(s.field, before, target)',
                     'case sound_op::n: add(s.field, before, n); break;', 'case sound_op::n2: add(s.field, before, 2 * n); break;',
                     'case sound_op::n8: add(s.field, before, 8 * n); break;',
                     'case sound_op::n16: add(s.field, before, (before & 0x80000000u) ? 0u - 16 * n : 16 * n); break;',
                     '#include "agent_capacity_frame_fields_5532d0.inc"', '#include "agent_capacity_frame_cave_5532d0.inc"',
                     'frame_sets.push_back({"1405532D0", frame_fields_e, frame_caves_e, proxy_frame_extra});',
                     'frame_sets.push_back({"1405532D0 (second array base)", frame_fields_e_base, frame_caves_none, proxy_frame_shift});',
                     'state_x, proxy_list, ai_pools[0].storage', 'scheduler::loop(proxy_list_meter, scheduler::main, 500ms);'):
            self.assertIn(text, self.cpp)
        body = self.cpp.split('void plan_proxy_list()')[1].split('void proxy_list_meter')[0]
        for op in {r['op'] for r in self.inc}:
            self.assertIn('sound_op::' + op, body, f'plan_proxy_list handles {op}')
        self.assertIn('constexpr std::uintptr_t proxy_stock_base[9] = {0, 0x144B473C0ull, 0x144B47830ull, 0x144B49270ull, 0x144B49B30ull, 0x144B4A3F0ull, 0x144B4A850ull, 0x144B4ACB0ull, 0x144B4B110ull};', self.cpp)
        self.assertIn('constexpr std::uint32_t proxy_entry_size[9] = {0, 8, 0x30, 16, 16, 8, 8, 8, 8};', self.cpp)
        self.assertEqual([ss.TABLES[k][0] for k in ('T0', 'T1', 'A', 'B', 'T3', 'T4', 'T5', 'T6')],
                         [0x144B473C0, 0x144B47830, 0x144B49270, 0x144B49B30, 0x144B4A3F0, 0x144B4A850, 0x144B4ACB0, 0x144B4B110])


class Code(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.image, cls.source = st.find_image()
        cls.table = json.load(open(JSON_ROWS, encoding='utf-8'))['rows']
        cls.cs = cp._cs()

    def setUp(self):
        if self.image is None:
            self.skipTest('no unpacked code files or analysed image on this machine')

    def reencode(self, r, value):
        raw = bytearray(self.image.read(r['at'], len(r['bytes']) // 2))
        struct.pack_into('<I', raw, r['field'] - r['at'], value & 0xFFFFFFFF)
        ins = next(self.cs.disasm(bytes(raw), r['at']))
        self.assertEqual(ins.size, len(raw), f"{r['at']:#x}: the re-encoded instruction changes length")
        return ins

    def mem_of(self, ins):
        from capstone import x86_const as X
        return next(o.mem for o in ins.operands if o.type == X.X86_OP_MEM)

    def imm_of(self, ins):
        from capstone import x86_const as X
        return [o.imm for o in ins.operands if o.type == X.X86_OP_IMM][-1]

    def test_every_row_is_the_shipped_instruction_with_the_stock_field(self):
        for r in self.table:
            raw = self.image.read(r['at'], len(r['bytes']) // 2)
            self.assertEqual(raw.hex(), r['bytes'], f"{r['at']:#x}: the shipped bytes differ from the table")
            ins = next(self.cs.disasm(raw, r['at']))
            self.assertEqual(ins.size, len(raw))
            off = r['field'] - r['at']
            self.assertTrue(0 <= off <= len(raw) - 4)
            got = struct.unpack_from('<I', raw, off)[0]
            if r['form'] == 1:
                self.assertEqual(got, (r['stock'] - (r['field'] + 4 + r['tail'])) & 0xFFFFFFFF, f"{r['field']:#x}: rip target")
                self.assertEqual(len(raw), off + 4 + r['tail'])
            else:
                self.assertEqual(got, r['stock'])

    def test_every_value_after_the_move(self):
        new_base, at = {}, 0x150100000
        for t in ('T0', 'T1', 'A', 'B', 'T3', 'T4', 'T5', 'T6'):
            new_base[t] = at
            at += ENTRIES * SIZES[t]
        self.assertEqual(at - 0x150100000, ENTRIES * 120)
        for r in self.table:
            row = f"{r['at']:#x} {r['text']}"
            if r['op'] == 'ref':
                target = new_base[r['table']] + r['offset']
                if r['form'] == 1:
                    ins = self.reencode(r, (target - (r['field'] + 4 + r['tail'])) & 0xFFFFFFFF)
                    mem = self.mem_of(ins)
                    self.assertEqual(ins.address + ins.size + mem.disp, target, row)
                else:
                    ins = self.reencode(r, (target - 0x140000000) & 0xFFFFFFFF)
                    self.assertEqual(self.mem_of(ins).disp, target - 0x140000000, row)
                # the stock role: the stock target is the stock base plus the same offset
                self.assertEqual((r['stock'] if r['form'] == 1 else 0x140000000 + r['stock']), ss.TABLES[r['table']][0] + r['offset'], row)
            else:
                mult = {'n': 1, 'n2': 2, 'n8': 8, 'n16': 16}[r['op']]
                neg = r['stock'] & 0x80000000
                want = -mult * ENTRIES if neg else mult * ENTRIES
                ins = self.reencode(r, want)
                if ins.mnemonic in ('imul', 'cmp', 'add'):
                    self.assertEqual(self.imm_of(ins), want, row)
                else:
                    self.assertEqual(self.mem_of(ins).disp, want, row)

    def test_the_offset_minus_four_rows_are_the_compaction_loop_forms(self):
        negative = [r for r in self.table if r['op'] == 'ref' and r['offset'] < 0]
        self.assertTrue(negative)
        for r in negative:
            self.assertEqual(r['offset'], -4)
            self.assertIn(r['table'], ('T3', 'T4', 'T5', 'T6'))
            self.assertTrue(0x140552DF0 <= r['at'] < 0x14055319F, 'only FUN_140552DF0 addresses `table - 4 + index`')

    def test_the_frame(self):
        plan = json.load(open(FRAME_JSON, encoding='utf-8'))
        self.assertEqual(plan['function'], '0x1405532d0')
        self.assertEqual(plan['extra'], EXTRA)
        self.assertEqual(plan['array_top'], 0xBB0)
        self.assertEqual(plan['frame']['stock_size'], 0xBC0)
        # layout: selected[] at 0xC0, the 16 byte array at 0x2F0 (stock) ending at the cookie 0xBB0
        self.assertEqual(0xC0 + 4 * STOCK, 0x2F0)
        self.assertEqual(0x2F0 + 16 * STOCK, 0xBB0)
        new_array = 0x2F0 + SHIFT
        self.assertLessEqual(0xC0 + 4 * ENTRIES, new_array, 'selected[] ends before the moved array')
        self.assertEqual(new_array + 16 * ENTRIES, 0xBB0 + EXTRA, 'the array ends at the moved cookie')
        # the three lea of the array base (stock 0x2F0) and the other uses of the two bases
        bases = [0x1405535AE, 0x140553822, 0x1405538DA]
        for at in bases:
            ins = next(self.cs.disasm(self.image.read(at, 8), at))
            self.assertEqual((ins.mnemonic, ins.size), ('lea', 8), hex(at))
            self.assertEqual(self.mem_of(ins).disp, 0x2F0)
        fields = parse_frame(open(os.path.join(NATIVE, 'agent_capacity_frame_fields_5532d0.inc'), encoding='utf-8').read())
        self.assertEqual(len(fields), 7)
        spans = [(f[0], f[0] + f[1], 'planner') for f in fields] + [(at + 4, at + 8, 'lea') for at in bases]
        cave = re.search(r'\{(0x[0-9a-f]+)ull', open(os.path.join(NATIVE, 'agent_capacity_frame_cave_5532d0.inc'), encoding='utf-8').read(), re.I)
        self.assertEqual(int(cave.group(1), 16), 0x1405532E0, 'the `sub rsp` window')
        spans.append((0x1405532E0, 0x1405532E7, 'cave window'))
        for r in self.table:
            spans.append((r['field'], r['field'] + 4, 'sound row'))
        spans.sort()
        self.assertEqual([(hex(a[0]), a[2], hex(b[0]), b[2]) for a, b in zip(spans, spans[1:]) if a[1] > b[0]], [])
        # the stock array accesses: every rsp-relative access between 0x2F0 and 0xBB0 is one of the three lea
        raw = self.image.read(0x1405532D0, 0x1405539A3 - 0x1405532D0)
        inside = []
        from capstone import x86_const as X
        for ins in self.cs.disasm(raw, 0x1405532D0):
            for o in ins.operands:
                if o.type == X.X86_OP_MEM and o.mem.base == X.X86_REG_RSP and 0x2F0 <= o.mem.disp < 0xBB0:
                    inside.append(ins.address)
        self.assertEqual(sorted(inside), sorted(bases), 'no other direct access between the two array tops')

    def test_the_remaining_frame_self_check(self):
        """The planner's own self-check ran when the plan was made; re-run it on the shipped image."""
        sys.path.insert(0, os.path.join(ROOT, 'ops', 'engine'))
        import frame_grow
        plan = json.load(open(FRAME_JSON, encoding='utf-8'))
        image = cp.open_image(cp.DEFAULT_IMAGE) if hasattr(cp, 'DEFAULT_IMAGE') and os.path.exists(cp.DEFAULT_IMAGE) else None
        if image is None:
            self.skipTest('analysed image missing')
        frame_grow.self_check(image, plan, extras=[EXTRA])


