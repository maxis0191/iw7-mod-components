"""The GSC variable pools (a46): every row of script_variables_sites.inc against the shipped code and against the new layout.

The .inc is generated by ops/engine/variable_sites.py from ops/engine/variable-sites.json. Offline checks:
  - the .inc, the JSON and the formulas of script_variables.hpp / .cpp agree;
  - every row is the shipped instruction with the stock field (needs the unpacked code or the analysed image: skipped without);
  - re-encoding every reference with arbitrary new table addresses decodes to the new table + the same offset (rip and register forms);
  - every `lea r,[s+s*4]` becomes `mov r,s` of the same length and the `shl` after it takes 0x10: the segment base is s * 0x10000;
  - every constant takes the value its meaning needs (bounds, the reciprocal multiply, the byte counts, the P8 -> CH distance / 16);
  - no row touches a byte another patch of the capacity component, a cave window or an iw7-mod hook window uses;
  - the sentinel scan: no 16-bit compare against 0xFFFF / -1 or sign test of a link, in the whole variable system (the widths are proven).
"""
