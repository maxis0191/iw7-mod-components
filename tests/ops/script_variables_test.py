STOCK = {'A': 0x14665A180, 'B': 0x146675980, 'P8': 0x146691180, 'P4': 0x1466FF180, 'CH': 0x146756180}
STOCK_BYTES = {'A': 0x1B800, 'B': 0x1B800, 'P8': 0x6E000, 'P4': 0x37000, 'CH': 0x3C0000}
N = 0x10000       # child entries a segment
PN = 0x40000      # parent ids (a56: 4 segments of 0x10000 locals)
NEW_BYTES = {'A': 2 * PN, 'B': 2 * PN, 'P8': 8 * PN, 'P4': 4 * PN, 'CH': 4 * N * 0x18}
# arbitrary storage addresses (16 byte aligned, 16 bytes apart in the real allocation): above the image, in the order the component reserves them
NEW = {}
_at = 0x150000010
for _k in ('A', 'B', 'P8', 'P4', 'CH'):
    NEW[_k] = _at
    _at += (NEW_BYTES[_k] + 32 + 4095) & ~4095
# hook windows of the iw7-mod scripting components over the variable system (client fork): their first bytes are a jump
HOOKS = [0x140C061F0, 0x140C09D20, 0x140C039F0, 0x140C09DA7, 0x140C09D37, 0x140C09D47, 0x140C0D0A4, 0x140C0D0B2, 0x140C0E5CE, 0x140C0E8EB,
         0x140C0E8F2, 0x140C0EA73, 0x140C0EA92, 0x140C0EB63, 0x140C0E9F5, 0x140C0F8C1]


def reloc(a):
    for k, b in STOCK.items():
        if b <= a < b + STOCK_BYTES[k]:
            return NEW[k] + a - b
    return a


def parse_inc(text):
    out = {}
    for name in ('REFS', 'IMMS', 'LEAS', 'SHLS'):
        body = re.search(r'#ifdef SCRIPT_VARIABLES_%s\n(.*?)#endif' % name, text, re.S).group(1)
        out[name] = [re.findall(r'0x[0-9A-Fa-f]+|\w+::\w+|-?\d+', line) for line in body.strip().split('\n') if line.strip()]
    return out


class Rows(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.text = open(INC, encoding='utf-8').read()
        cls.rows = parse_inc(cls.text)
        cls.data = json.load(open(JSON_ROWS, encoding='utf-8'))
        cls.hpp = open(HPP, encoding='utf-8').read()
        cls.cpp = open(CPP, encoding='utf-8').read()

    def test_the_inc_is_the_json(self):
        d = self.data
        self.assertEqual(len(self.rows['REFS']), len(d['refs']))
        self.assertEqual(len(self.rows['IMMS']), len(d['imms']))
        self.assertEqual(len(self.rows['LEAS']), len(self.rows['SHLS']))
        self.assertEqual(len(self.rows['LEAS']) * 2, len(d['pairs']))
        got = sorted(int(r[0], 16) for r in self.rows['REFS'])
        self.assertEqual(got, sorted(r['field'] for r in d['refs']))
        for r in d['refs']:
            self.assertLessEqual(r['target'] - STOCK[r['region']] if r['region'] in STOCK else 0, 0x1F)

    def test_the_hpp_layout(self):
        self.assertIn('child_entries = 0x10000', self.hpp)
        self.assertIn('parent_ids = 0x40000', self.hpp)
        self.assertIn('stock_child_entries = 0xA000, stock_parent_ids = 0xDC00', self.hpp)
        # the u16 fields hold every index and id; the names of object keys stay below the integer key base
        self.assertLessEqual(0x40000 + PN, 0x800000)
        self.assertEqual(NEW_BYTES['CH'], 0x600000)

    def test_the_cpp_applies_the_table(self):
        for op in ('hash_half', 'child_bound', 'parent_bound', 'name_bound', 'recip', 'p4_bytes', 'p2_bytes', 'idiom16', 'int_low', 'int_high'):
            self.assertIn('case script_op::%s' % op, self.cpp)
        self.assertIn('add(field, 0xD, 0x10, 1)', self.cpp)
        self.assertIn('0x80000000u', self.cpp)

    def test_the_ops_are_the_constants_by_meaning(self):
        by = {}
        for r in self.data['imms']:
            by.setdefault(r['op'], []).append(r)
        self.assertEqual({k: len(v) for k, v in by.items()},
                         {'child_bound': 2, 'parent_bound': 5, 'name_bound': 8, 'recip': 4, 'p4_bytes': 1, 'p2_bytes': 2, 'idiom16': 4, 'hash_half': 2, 'int_low': 5, 'int_high': 5})
        # the reciprocal: hi32(seg * 0x10000 * 0x80000000) >> 15 == seg ; the stock: hi32(seg * 0xA000 * 0xCCCCCCCD) >> 15 == seg
        for seg in range(4):
            self.assertEqual(((seg * 0x10000 * 0x80000000) >> 32) >> 15, seg)
            self.assertEqual(((seg * 0xA000 * 0xCCCCCCCD) >> 32) >> 15, seg)
        # the P8 -> CH distance: stock 0xC5000, as lea k / lea 3x / *8: 24 * x + 16 * k
        self.assertEqual((STOCK['CH'] - STOCK['P8']) // 16, 0xC500)
        self.assertEqual((NEW['CH'] - NEW['P8']) % 16, 0)
        # the bucket index of 0x140C04E53 / 0x140C06114 is added in units of 2 bytes: stock (hash - P8) / 2 = 0x52800
        self.assertEqual((0x146736180 - STOCK['P8']) // 2, 0x52800)

    def test_no_overlap_with_any_other_patch(self):
        spans = []
        for r in self.data['refs']:
            spans.append((r['field'], r['field'] + 4, 'ref'))
        for r in self.data['imms']:
            spans.append((r['field'], r['field'] + 4, 'imm'))
        for r in self.data['pairs']:
            spans.append((r['at'], r['at'] + r['len'], 'lea') if r['op'] == 'seg_lea' else (r['field'], r['field'] + 1, 'shl'))
        mine = sorted(spans)
        self.assertEqual([(hex(a[0]), hex(b[0])) for a, b in zip(mine, mine[1:]) if a[1] > b[0]], [], 'own rows overlap')
        others = []
        cpp = open(os.path.join(ROOT, 'src', 'native', 'agent_capacity.cpp'), encoding='utf-8').read()
        sites, _ = st.extract_sites(cpp)
        for x in sites:
            width = 4 if x['kind'] == 'rip' else (len(x['before']) if x['kind'] == 'block' else x['width'])
            others.append((x['address'], x['address'] + width, 'site'))
        for name in ('agent_capacity_caves.inc', 'agent_capacity_caves_rewind.inc', 'agent_capacity_caves_wide.inc', 'agent_capacity_caves_mask.inc',
                     'agent_capacity_caves_guard.inc', 'agent_capacity_caves_interp.inc'):
            for c in st.parse_inc(open(os.path.join(ROOT, 'src', 'native', name), encoding='utf-8').read()):
                others.append((c['start'], c['start'] + len(c['old']), 'cave ' + name))
                others.extend((t['field'], t['field'] + 4, 'retarget') for t in c['retargets'])
        for name in ('agent_capacity_state.inc', 'agent_capacity_pools.inc'):
            for m in re.finditer(r'^\{(0x[0-9A-F]+)ull,', open(os.path.join(ROOT, 'src', 'native', name), encoding='utf-8').read(), re.M):
                others.append((int(m.group(1), 16), int(m.group(1), 16) + 4, name))
        clash = [(hex(a[0]), a[2], hex(b[0]), b[2]) for a in mine for b in others if a[0] < b[1] and b[0] < a[1]]
        self.assertEqual(clash, [])
        for h in HOOKS:
            near = [hex(a[0]) for a in mine if a[0] < h + 16 and h < a[1]]
            self.assertEqual(near, [], 'a row inside the first 16 bytes of the mod hook at %X' % h)


class Code(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.image, cls.source = st.find_image()
        cls.data = json.load(open(JSON_ROWS, encoding='utf-8'))
        cls.cs = cp._cs()

    def setUp(self):
        if self.image is None:
            self.skipTest('no unpacked code files or analysed image on this machine')

    def test_every_row_is_the_shipped_instruction_with_the_stock_field(self):
        for r in self.data['refs'] + self.data['imms']:
            raw = self.image.read(r['at'], len(r['bytes']) // 2) if 'bytes' in r else self.image.read(r['at'], 8)
            if 'bytes' in r:
                self.assertEqual(raw.hex(), r['bytes'], hex(r['at']))
            got = struct.unpack_from('<I', self.image.read(r['field'], 4))[0]
            if r['op'] == 'ref':
                want = (r['target'] - (r['field'] + 4 + r['tail'])) if r['form'] == 'rip' else (r['target'] - r['base'])
                self.assertEqual(got, want & 0xFFFFFFFF, hex(r['field']))
            else:
                self.assertEqual(got, r['stock'], hex(r['field']))
        for r in self.data['pairs']:
            if r['op'] == 'seg_lea':
                self.assertEqual(self.image.read(r['at'], r['len']).hex(), r['before'])
            else:
                self.assertEqual(self.image.read(r['field'], 1)[0], 0xD)

    def test_every_reference_decodes_to_the_new_table(self):
        from capstone import x86_const as X
        for r in self.data['refs']:
            raw = bytearray(self.image.read(r['at'], len(r['bytes']) // 2))
            off = r['field'] - r['at']
            if r['form'] == 'rip':
                new = (reloc(r['target']) - (r['field'] + 4 + r['tail'])) & 0xFFFFFFFF
            else:
                new = (reloc(r['target']) - reloc(r['base'])) & 0xFFFFFFFF
            struct.pack_into('<I', raw, off, new)
            ins = next(self.cs.disasm(bytes(raw), r['at']))
            self.assertEqual(ins.size, len(raw), hex(r['at']))
            mem = next(o.mem for o in ins.operands if o.type == X.X86_OP_MEM)
            if r['form'] == 'rip':
                self.assertEqual(r['at'] + ins.size + mem.disp, reloc(r['target']), hex(r['at']))
            else:
                self.assertEqual(reloc(r['base']) + mem.disp, reloc(r['target']), hex(r['at']))
            self.assertTrue(-0x80000000 <= mem.disp < 0x80000000)

    def test_every_pair_is_the_segment_base_times_0x10000(self):
        pairs = {}
        for r in self.data['pairs']:
            pairs.setdefault(r['func'], []).append(r)
        lea = [r for r in self.data['pairs'] if r['op'] == 'seg_lea']
        shl = [r for r in self.data['pairs'] if r['op'] == 'seg_shl']
        self.assertEqual(len(lea), len(shl))
        for r in lea:
            old = next(self.cs.disasm(bytes.fromhex(r['before']), r['at']))
            new = list(self.cs.disasm(bytes.fromhex(r['after']), r['at']))
            self.assertEqual(old.mnemonic, 'lea')
            self.assertEqual(new[0].mnemonic, 'mov')
            self.assertTrue(all(i.mnemonic == 'nop' for i in new[1:]))
            self.assertEqual(sum(i.size for i in new), old.size)
            self.assertEqual(old.operands[0].reg and old.reg_name(old.operands[0].reg).lstrip('re'), new[0].reg_name(new[0].operands[0].reg).lstrip('re'))
        for r in shl:
            ins = next(self.cs.disasm(bytes.fromhex(r['bytes']), r['at']))
            self.assertEqual(ins.mnemonic, 'shl')
            self.assertEqual(ins.operands[1].imm, 0xD)
            self.assertEqual(r['field'] - r['at'], ins.size - 1)

    def test_the_sentinel_scan_of_the_variable_system(self):
        """No code of the variable system compares a link or an id against 0xFFFF / -1 or tests its sign: the widths of the u16 fields are the new
        bounds. The known 16-bit range checks are the integer-key serializer (`lea eax,[rbx+0x8000]; cmp eax,0xFFFF`: a short fits) and the
        decrements `add ax,0xFFFF`; AllocVariable's `cmp eax,-1` is an unsigned minimum search."""
        import sqlite3
        lab = os.environ.get('IW7_RE_LAB', os.path.join(os.path.expanduser('~'), 'Documents', 'IW7-RE-Lab'))
        db_file = os.path.join(lab, 'engine', 'iw7-engine.sqlite')
        if not os.path.exists(db_file):
            self.skipTest('no engine database')
        db = sqlite3.connect('file:' + db_file.replace('\\', '/') + '?mode=ro', uri=True)
        num = lambda x: x if isinstance(x, int) else int(x, 16)
        found = set()
        for a, e in db.execute('select addr,end from functions'):
            a, e = num(a), num(e)
            if not (0x140BFE000 <= a < 0x140C11000):
                continue
            for ins in self.cs.disasm(self.image.read(a, e - a), a):
                t = ins.mnemonic + ' ' + ins.op_str
                if re.search(r'\b(cmp|test|and|or|mov|sub|add) .*(0xffff\b|, -1$)', t) and not re.search(r'dword ptr|qword ptr|\b(r[a-z0-9]+|e[a-z]+)\b, 0xffffffff', t):
                    found.add(ins.address)
        known = {0x140C00310, 0x140C01420, 0x140BFE727, 0x140BFF293, 0x140C02B53, 0x140C02ED1, 0x140C0529E, 0x140C046CD,
             0x140C0AC0F, 0x140C0CE1F, 0x140C0CF92, 0x140C0E95D}    # loop counters (add edi, -1)
        self.assertEqual(sorted(hex(x) for x in found - known), [], 'a new 16-bit sentinel candidate in the variable system')


