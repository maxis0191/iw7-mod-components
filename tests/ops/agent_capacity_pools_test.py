"""The scriptable stream buffer pools (a43): every table row, for every accepted agent count, against the shipped code.

agent_capacity_pools.inc (generated by ops/engine/pool_sites.py from pool-sites.json) lists the 4-byte instruction fields of the five static
pools of scriptable stream buffers (16, 64, 256, 512, 3072 byte blocks; stock 128, 128, 64, 32, 32 blocks; one server pool and two client slots a
class): array bases, free-list heads (an array is followed by its 8 byte head), slot strides (array + 8) and array sizes. Offline, for n = 24..232:
  - the .inc and the JSON agree, every row's instruction is the shipped one and its field holds the stock value;
  - the value each row receives is the one the layout of agent_capacity.hpp gives (the formulas are pinned); re-encoding the instruction decodes to
    the intended displacement / immediate / rip target, the new head is exactly one array behind the new base;
  - the pools hold as many blocks as there are reserved scriptable records in every class (an instance holds one buffer: no class can run out);
  - no row touches a field another patch, cave window or retarget uses.
Skipped when neither the unpacked code files nor the analysed image exist on the machine.
"""
import importlib.util
import json
import os
import re
import struct
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
HPP = os.path.join(ROOT, 'src', 'native', 'agent_capacity.hpp')
CPP = os.path.join(ROOT, 'src', 'native', 'agent_capacity.cpp')
INC = os.path.join(ROOT, 'src', 'native', 'agent_capacity_pools.inc')
JSON_ROWS = os.path.join(ROOT, 'ops', 'engine', 'pool-sites.json')

spec = importlib.util.spec_from_file_location('sites_test', os.path.join(HERE, 'agent_capacity_sites_test.py'))
st = importlib.util.module_from_spec(spec)
spec.loader.exec_module(st)
cp = st.cp
spec = importlib.util.spec_from_file_location('pool_sites', os.path.join(ROOT, 'ops', 'engine', 'pool_sites.py'))
ps = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ps)

COUNTS = list(range(24, 233, 4))
BASE = 0x140000000
CLASS_BYTES = (16, 64, 256, 512, 3072)
STOCK_BLOCKS = (128, 128, 64, 32, 32)


def records(n):
    return max(200, 24 + n + 32)


def blocks(n):
    return max(512, records(n))


def array_bytes(n, c):
    return blocks(n) * CLASS_BYTES[c]


def parse_rows(text):
    rows = []
    for m in re.finditer(r'^\{(0x[0-9A-F]+)ull, (\d), (0x[0-9A-F]+)(?:ull|u), (\d+), pool_op::(\w+), (\d)\},$', text, re.M):
        rows.append({'field': int(m.group(1), 16), 'form': int(m.group(2)), 'stock': int(m.group(3), 16), 'tail': int(m.group(4)),
                     'op': m.group(5), 'cls': int(m.group(6))})
    return rows


class PoolRows(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.image, cls.source = st.find_image()
        cls.hpp = open(HPP, encoding='utf-8').read()
        cls.cpp = open(CPP, encoding='utf-8').read()
        cls.inc = parse_rows(open(INC, encoding='utf-8').read())
        cls.table = json.load(open(JSON_ROWS, encoding='utf-8'))['rows']
        cls.cs = cp._cs()

    def test_the_hpp_formulas(self):
        for text in ('constexpr std::uint32_t stream_pool_classes = 5, stream_pool_slots = 2, stream_pool_min_blocks = 512;',
                     'constexpr std::uint32_t stream_pool_class_bytes[stream_pool_classes] = {16, 64, 256, 512, 3072};',
                     'constexpr std::uint32_t stock_stream_pool_blocks[stream_pool_classes] = {128, 128, 64, 32, 32};',
                     'return records > stream_pool_min_blocks ? records : stream_pool_min_blocks;',
                     'stream_pool_blocks(agents) * stream_pool_class_bytes[cls]',
                     'stream_pool_array_bytes(agents, cls) + 8;'):
            self.assertIn(text, self.hpp)
        self.assertEqual(ps.CLASS_BYTES, CLASS_BYTES)
        self.assertEqual(ps.STOCK_COUNT, STOCK_BLOCKS)

    def test_every_class_holds_a_block_for_every_reserved_record(self):
        for n in COUNTS:
            for c in range(5):
                self.assertGreaterEqual(blocks(n), records(n), f'{n} agents: class {c} holds one block for each record')
                self.assertGreaterEqual(blocks(n), STOCK_BLOCKS[c])
                self.assertEqual(array_bytes(n, c) % CLASS_BYTES[c], 0)
        # memory: one set (array + head, all classes) at the largest count
        total = sum(array_bytes(232, c) + 8 for c in range(5))
        self.assertLess(total, 2 * 1024 * 1024)

    def test_the_inc_is_the_json(self):
        self.assertEqual(len(self.inc), len(self.table))
        self.assertEqual(len(self.inc), 132)
        for a, b in zip(self.inc, self.table):
            self.assertEqual((a['field'], a['form'], a['stock'], a['tail'], a['op'], a['cls']), (b['field'], b['form'], b['stock'], b['tail'], b['op'], b['cls']))
        self.assertEqual([r['field'] for r in self.inc], sorted(r['field'] for r in self.inc))
        self.assertEqual(len({r['field'] for r in self.inc}), len(self.inc), 'one row a field')
        enum = re.search(r'enum class pool_op[^{]*\{([^}]*)\}', self.cpp).group(1)
        names = re.findall(r'\w+', enum)
        for op in {r['op'] for r in self.inc}:
            self.assertIn(op, names)

    def test_every_class_is_covered_by_every_kind_of_row(self):
        by = {}
        for r in self.table:
            by.setdefault(r['op'], set()).add(r['cls'])
        for op in ('ref_server_base', 'ref_server_head', 'ref_client_base', 'ref_client_head', 'pool_stride', 'pool_array'):
            self.assertEqual(by.get(op), {0, 1, 2, 3, 4}, op)
        # stride and size rows carry the stock value of their class
        for r in self.table:
            if r['op'] == 'pool_stride':
                self.assertEqual(r['stock'], ps.CLIENT_STRIDE[r['cls']])
            if r['op'] == 'pool_array':
                self.assertEqual(abs(struct.unpack('<i', struct.pack('<I', r['stock']))[0]), ps.CLIENT_ARRAY[r['cls']])
        # the five initialisers (server) and the five client slot initialisers each hold a base/head/stride row of their class
        starts = {r['at'] for r in self.table}
        for init in ps.RANGES[0:1]:
            pass
        for c in range(5):
            self.assertIn(0x14001A3D0 + 0x40 * c, starts, f'server initialiser of class {c} (lea rax, head)')

    def test_the_cpp_applies_the_table(self):
        for text in ('plan_pools();', '#include "agent_capacity_pools.inc"', 'pool_server[c] = reserve(stream_pool_array_bytes(agents, c) + 8);',
                     'pool_client[c] = reserve(static_cast<std::size_t>(stream_pool_slots) * stream_pool_stride(agents, c));',
                     'pool_op::ref_server_head: rip(s.field, static_cast<std::uintptr_t>(s.stock), pool_server[s.cls].data + array, s.tail)',
                     'pool_op::ref_client_head: rip(s.field, static_cast<std::uintptr_t>(s.stock), pool_client[s.cls].data + array, s.tail)',
                     'pool_op::pool_stride: add(s.field, before, stream_pool_stride(agents, s.cls))',
                     'chain_pool(pool_server[c].data, stream_pool_blocks(agents), stream_pool_class_bytes[c]);',
                     'chain_pool(pool_client[c].data + static_cast<std::uintptr_t>(slot) * stream_pool_stride(agents, c)',
                     'exceed the %u blocks of each stream buffer class'):
            self.assertIn(text, self.cpp)
        body = self.cpp.split('void plan_pools()')[1].split('// ---- 3d.')[0]
        for op in {r['op'] for r in self.inc}:
            self.assertIn('pool_op::' + op, body, f'plan_pools handles {op}')
        self.assertIn('buffer pool_server[stream_pool_classes], pool_client[stream_pool_classes];', self.cpp)

    def test_no_overlap_with_any_other_patch(self):
        sites, _ = st.extract_sites(self.cpp)
        spans = []
        for x in sites:
            width = 4 if x['kind'] == 'rip' else (len(x['before']) if x['kind'] == 'block' else x['width'])
            spans.append((x['address'], x['address'] + width, 'site'))
        for name in ('agent_capacity_caves.inc', 'agent_capacity_caves_rewind.inc', 'agent_capacity_caves_wide.inc',
                     'agent_capacity_caves_mask.inc', 'agent_capacity_caves_guard.inc', 'agent_capacity_caves_interp.inc'):
            for c in st.parse_inc(open(os.path.join(ROOT, 'src', 'native', name), encoding='utf-8').read()):
                spans.append((c['start'], c['start'] + len(c['old']), 'cave ' + name))
                spans.extend((t['field'], t['field'] + 4, 'retarget') for t in c['retargets'])
        for r in self.inc:
            spans.append((r['field'], r['field'] + 4, 'pool row'))
        # the state rows too
        state = open(os.path.join(ROOT, 'src', 'native', 'agent_capacity_state.inc'), encoding='utf-8').read()
        for m in re.finditer(r'^\{(0x[0-9A-F]+)ull,', state, re.M):
            spans.append((int(m.group(1), 16), int(m.group(1), 16) + 4, 'state row'))
        spans.sort()
        clash = [(hex(a[0]), a[2], hex(b[0]), b[2]) for a, b in zip(spans, spans[1:]) if a[1] > b[0]]
        self.assertEqual(clash, [])


class ChainMirror(unittest.TestCase):
    def test_the_chain_is_what_the_static_initialiser_builds(self):
        """chain_pool (agent_capacity.cpp) mirrored on a byte array: block i -> block i + 1, last -> head, head -> block 0; alloc pops, free pushes."""
        size, blocks = 256, 6
        mem = {}
        array, head = 0x1000, 0x1000 + blocks * size
        nxt = head
        for i in range(blocks - 1, -1, -1):
            mem[array + i * size] = nxt
            nxt = array + i * size
        mem[head] = nxt
        seen, p = [], mem[head]
        while p != head:
            seen.append(p)
            p = mem[p]
        self.assertEqual(seen, [array + i * size for i in range(blocks)])
        # alloc: pop the head, and an empty list holds its own address
        for _ in range(blocks):
            p = mem[head]
            mem[head] = mem[p]
        self.assertEqual(mem[head], head)


class PoolCode(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.image, cls.source = st.find_image()
        cls.table = json.load(open(JSON_ROWS, encoding='utf-8'))['rows']
        cls.cs = cp._cs()

    def setUp(self):
        if self.image is None:
            self.skipTest('no unpacked code files or analysed image on this machine')

    def reencode(self, r, value):
        raw = bytearray(self.image.read(r['at'], len(r['bytes']) // 2))
        struct.pack_into('<I', raw, r['field'] - r['at'], value & 0xFFFFFFFF)
        ins = next(self.cs.disasm(bytes(raw), r['at']))
        self.assertEqual(ins.size, len(raw), f"{r['at']:#x}: the re-encoded instruction changes length")
        return ins

    def disp_of(self, ins):
        from capstone import x86_const as X
        mem = next(o.mem for o in ins.operands if o.type == X.X86_OP_MEM)
        return mem.disp, mem.base == X.X86_REG_RIP

    def imm_of(self, ins):
        from capstone import x86_const as X
        return [o.imm for o in ins.operands if o.type == X.X86_OP_IMM][-1]

    def test_every_row_is_the_shipped_instruction_with_the_stock_field(self):
        for r in self.table:
            raw = self.image.read(r['at'], len(r['bytes']) // 2)
            self.assertEqual(raw.hex(), r['bytes'], f"{r['at']:#x}: the shipped bytes differ from the table")
            ins = next(self.cs.disasm(raw, r['at']))
            self.assertEqual(ins.size, len(raw))
            off = r['field'] - r['at']
            self.assertTrue(0 <= off <= len(raw) - 4)
            got = struct.unpack_from('<I', raw, off)[0]
            if r['form'] == 1:
                self.assertEqual(got, (r['stock'] - (r['field'] + 4 + r['tail'])) & 0xFFFFFFFF, f"{r['field']:#x}: rip target")
                self.assertEqual(len(raw), off + 4 + r['tail'])
            else:
                self.assertEqual(got, r['stock'])

    def test_every_value_for_every_count(self):
        server_base = {c: 0x150100000 + c * 0x400000 for c in range(5)}
        client_base = {c: 0x150800000 + c * 0x800000 for c in range(5)}
        for n in COUNTS:
            for r in self.table:
                c, op, stock = r['cls'], r['op'], r['stock']
                row = f"{n} agents, {r['at']:#x} {r['text']}"
                arr = array_bytes(n, c)
                if op == 'pool_stride':
                    self.assertEqual(self.imm_of(self.reencode(r, arr + 8)), arr + 8, row)
                    self.assertEqual(arr + 8, blocks(n) * CLASS_BYTES[c] + 8)
                elif op == 'pool_array':
                    want = -arr if stock & 0x80000000 else arr
                    ins = self.reencode(r, want)
                    self.assertEqual(self.disp_of(ins)[0], want, row)
                else:
                    server = 'server' in op
                    head = op.endswith('head')
                    new_base = (server_base if server else client_base)[c]
                    target = new_base + (arr if head else 0)
                    rel = (target - (r['field'] + 4 + r['tail'])) & 0xFFFFFFFF
                    ins = self.reencode(r, rel)
                    disp, rip = self.disp_of(ins)
                    self.assertTrue(rip, row)
                    self.assertEqual(ins.address + ins.size + disp, target, row)
                    # the stock role: a head sits one array behind its base
                    if head:
                        self.assertEqual(stock, (ps.SERVER_BASE if server else ps.CLIENT_BASE)[c] + STOCK_BLOCKS[c] * CLASS_BYTES[c])

    def test_the_initialisers_still_chain_a_whole_array(self):
        """The server initialiser of class c walks `rax = head; while (rax -= block, [rax] = prev, rax > base)`: the array holds whole blocks only."""
        for c in range(5):
            init = 0x14001A3D0 + 0x40 * c
            code = self.image.read(init, 0x40)
            ins = list(self.cs.disasm(code, init))
            self.assertEqual(ins[0].mnemonic, 'lea')
            sub = next(i for i in ins if i.mnemonic == 'sub' and i.op_str.startswith('rax,'))
            self.assertEqual(int(sub.op_str.split(',')[1], 16), CLASS_BYTES[c])
        for n in COUNTS:
            for c in range(5):
                self.assertEqual(array_bytes(n, c) % CLASS_BYTES[c], 0)

    def test_the_lookup_ranges_do_not_overlap_across_slots(self):
        for n in COUNTS:
            for c in range(5):
                stride = array_bytes(n, c) + 8
                self.assertEqual(stride - array_bytes(n, c), 8, 'slot 1 starts right after slot 0 head')


